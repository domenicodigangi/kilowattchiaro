"""Engine defaults: every setting the engine reads, with production's default.

Generated by the export from the private service settings. Override any of them
with an environment variable prefixed ``KWC_ENGINE_`` (for example
``KWC_ENGINE_DEFAULT_RID_PRICE_EUR_KWH=0.05``) or by constructing
``EngineSettings`` explicitly. The dated money inputs live in
``assumptions.yaml``.
"""

from pydantic_settings import BaseSettings, SettingsConfigDict

from .assumptions import value as _assumption


class EngineSettings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="KWC_ENGINE_", extra="ignore")

    default_rid_price_eur_kwh: float = _assumption("rid_minimum_price")  # GSE RID PMG
    default_self_consumption_ratio: float = 0.30  # Without battery
    default_self_consumption_ratio_battery: float = 0.70  # With battery
    default_maintenance_eur_yr: float = 75.0
    default_inverter_replacement_eur: float = 1750.0
    default_inverter_replacement_year: int = 11
    default_battery_replacement_year: int = 14  # Modern LFP: 6000+ cycles, ~16yr to 80% SOH
    default_panel_degradation_pct: float = 0.005
    default_battery_fade_pct: float = 0.02


settings = EngineSettings()
